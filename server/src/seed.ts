/**
 * Seeds a demo workspace: 6 users, one team, 3 projects, ~220 issues spread over the last
 * 10 weeks, plus comments, activity and notifications. Re-running replaces only the demo data
 * (users @sprintly.dev and their team), never anything else in the database.
 *
 *   npm run seed
 *   login: demo@sprintly.dev / password123
 */
import bcrypt from 'bcryptjs';
import { Types } from 'mongoose';
import { ISSUE_PRIORITIES, ISSUE_STATUSES, ORDER_STEP, PRIORITY_RANK, type IssueStatus } from '@sprintly/shared';
import { env } from './config/env';
import { connectDb, disconnectDb } from './db';
import {
  ActivityModel,
  CommentModel,
  IssueModel,
  NotificationModel,
  ProjectModel,
  TeamModel,
  UserModel,
} from './models';

const DAY = 864e5;
let seed = 42;
const rand = () => ((seed = (seed * 16807) % 2147483647) - 1) / 2147483646; // deterministic
const pick = <T,>(arr: readonly T[]) => arr[Math.floor(rand() * arr.length)]!;
const chance = (p: number) => rand() < p;

const PEOPLE = [
  { name: 'Demo User', email: 'demo@sprintly.dev', title: 'Engineering Lead', avatarColor: '#6366f1' },
  { name: 'Ava Chen', email: 'ava@sprintly.dev', title: 'Frontend Engineer', avatarColor: '#ec4899' },
  { name: 'Marcus Reid', email: 'marcus@sprintly.dev', title: 'Backend Engineer', avatarColor: '#14b8a6' },
  { name: 'Priya Natarajan', email: 'priya@sprintly.dev', title: 'Product Designer', avatarColor: '#f59e0b' },
  { name: 'Leo Fischer', email: 'leo@sprintly.dev', title: 'QA Engineer', avatarColor: '#8b5cf6' },
  { name: 'Sofia Alvarez', email: 'sofia@sprintly.dev', title: 'Product Manager', avatarColor: '#0ea5e9' },
];

const VERBS = ['Add', 'Fix', 'Refactor', 'Improve', 'Investigate', 'Implement', 'Polish', 'Remove', 'Optimise', 'Document'];
const THINGS = [
  'onboarding flow', 'password reset email', 'Kanban drag performance', 'dark mode contrast', 'CSV export',
  'webhook retries', 'search ranking', 'notification batching', 'mobile navigation', 'rate limiting',
  'billing page', 'audit log', 'SSO login', 'empty states', 'date picker a11y', 'API pagination',
  'image uploads', 'error boundaries', 'slow dashboard query', 'keyboard shortcuts', 'invite flow',
  'timezone handling', 'session expiry', 'markdown preview', 'flaky e2e tests', 'Docker build cache',
];
const COMMENTS = [
  'I can take this one after the current sprint.',
  'Repro steps: open the board, drag quickly between columns. Happens ~1 in 5 times.',
  'Should we split this into frontend and backend tasks?',
  'Pushed a draft PR, would appreciate an early look.',
  'Design is ready in Figma, linked in the description.',
  'This is blocking the release, bumping priority.',
  'Looks good to me 👍',
  'Can we add a test for the edge case with empty columns?',
  'Confirmed fixed on staging.',
];

async function main() {
  await connectDb(env.MONGODB_URI);

  // ---- Remove previous demo data only ----
  const oldUsers = await UserModel.find({ email: /@sprintly\.dev$/ }, { _id: 1 }).lean();
  const oldTeams = await TeamModel.find({ name: 'Sprintly Demo' }, { _id: 1 }).lean();
  const oldProjects = await ProjectModel.find({ team: { $in: oldTeams.map((t) => t._id) } }, { _id: 1 }).lean();
  const pIds = oldProjects.map((p) => p._id);
  await Promise.all([
    IssueModel.deleteMany({ project: { $in: pIds } }),
    CommentModel.deleteMany({ project: { $in: pIds } }),
    ActivityModel.deleteMany({ project: { $in: pIds } }),
    NotificationModel.deleteMany({ user: { $in: oldUsers.map((u) => u._id) } }),
    ProjectModel.deleteMany({ _id: { $in: pIds } }),
    TeamModel.deleteMany({ _id: { $in: oldTeams.map((t) => t._id) } }),
    UserModel.deleteMany({ _id: { $in: oldUsers.map((u) => u._id) } }),
  ]);

  // ---- Users & team ----
  const passwordHash = await bcrypt.hash('password123', 10);
  const users = await UserModel.insertMany(PEOPLE.map((p) => ({ ...p, passwordHash })));
  const roles = ['owner', 'admin', 'member', 'member', 'member', 'viewer'] as const;
  const team = await TeamModel.create({
    name: 'Sprintly Demo',
    description: 'Demo workspace generated by the seed script',
    members: users.map((u, i) => ({ user: u._id, role: roles[i], joinedAt: new Date(Date.now() - 80 * DAY) })),
  });

  const now = Date.now();
  const projectDefs = [
    { name: 'Web App', key: 'WEB', color: '#6366f1', description: 'Customer-facing React application', n: 110 },
    { name: 'Platform API', key: 'API', color: '#14b8a6', description: 'Core REST + realtime services', n: 70 },
    { name: 'Mobile Launch', key: 'MOB', color: '#f59e0b', description: 'iOS & Android v1 launch', n: 40 },
  ];

  const activityDocs: Record<string, unknown>[] = [];
  const commentDocs: Record<string, unknown>[] = [];

  for (const def of projectDefs) {
    const labels = [
      { _id: new Types.ObjectId(), name: 'Bug', color: '#ef4444' },
      { _id: new Types.ObjectId(), name: 'Feature', color: '#6366f1' },
      { _id: new Types.ObjectId(), name: 'Improvement', color: '#14b8a6' },
      { _id: new Types.ObjectId(), name: 'Design', color: '#ec4899' },
      { _id: new Types.ObjectId(), name: 'Tech debt', color: '#64748b' },
    ];
    const project = await ProjectModel.create({
      team: team._id,
      name: def.name,
      key: def.key,
      color: def.color,
      description: def.description,
      labels,
      startDate: new Date(now - 70 * DAY),
      targetDate: new Date(now + (20 + Math.floor(rand() * 40)) * DAY),
      issueCounter: def.n,
      createdBy: users[0]!._id,
    });

    const orderByStatus: Record<IssueStatus, number> = { backlog: 0, todo: 0, in_progress: 0, in_review: 0, done: 0 };
    const issues = Array.from({ length: def.n }, (_, idx) => {
      const number = idx + 1;
      const createdAt = new Date(now - Math.floor(rand() * 70) * DAY - Math.floor(rand() * DAY));
      const age = (now - createdAt.getTime()) / DAY;
      // Older issues are more likely to be done, so the throughput chart looks realistic.
      const status: IssueStatus = chance(Math.min(0.85, age / 60)) ? 'done' : pick(ISSUE_STATUSES.slice(0, 4));
      const priority = pick(ISSUE_PRIORITIES);
      orderByStatus[status] += ORDER_STEP;
      const completedAt = status === 'done' ? new Date(createdAt.getTime() + rand() * Math.max(1, age - 1) * DAY) : null;
      const assignees = chance(0.85) ? [pick(users.slice(0, 5))._id] : [];
      if (chance(0.15)) assignees.push(pick(users.slice(0, 5))._id);
      const uniqueAssignees = [...new Map(assignees.map((a) => [a.toString(), a])).values()];
      const dueDate = chance(0.6) ? new Date(now + (Math.floor(rand() * 50) - 15) * DAY) : null;
      return {
        _id: new Types.ObjectId(),
        project: project._id,
        number,
        identifier: `${def.key}-${number}`,
        title: `${pick(VERBS)} ${pick(THINGS)}`,
        description: chance(0.6) ? 'Context, acceptance criteria and links go here.\n\n- [ ] Spec\n- [ ] Implement\n- [ ] Test' : '',
        status,
        priority,
        priorityRank: PRIORITY_RANK[priority],
        statusRank: ISSUE_STATUSES.indexOf(status),
        order: orderByStatus[status],
        labels: chance(0.8) ? [pick(labels)._id] : [],
        assignees: uniqueAssignees,
        reporter: pick(users)._id,
        dueDate,
        estimate: chance(0.5) ? pick([1, 2, 3, 5, 8]) : null,
        completedAt,
        commentCount: 0,
        createdAt,
        updatedAt: completedAt ?? createdAt,
      };
    });

    for (const issue of issues) {
      const n = chance(0.35) ? 1 + Math.floor(rand() * 3) : 0;
      issue.commentCount = n;
      for (let c = 0; c < n; c++) {
        const createdAt = new Date(issue.createdAt.getTime() + (c + 1) * rand() * 2 * DAY);
        commentDocs.push({ issue: issue._id, project: project._id, author: pick(users)._id, body: pick(COMMENTS), createdAt, updatedAt: createdAt });
      }
      const snap = { identifier: issue.identifier, title: issue.title };
      activityDocs.push({ actor: issue.reporter, verb: 'issue.created', team: team._id, project: project._id, issue: issue._id, issueSnapshot: snap, changes: [], createdAt: issue.createdAt });
      if (issue.completedAt) {
        activityDocs.push({
          actor: issue.assignees[0] ?? issue.reporter,
          verb: 'issue.moved',
          team: team._id,
          project: project._id,
          issue: issue._id,
          issueSnapshot: snap,
          changes: [{ field: 'status', from: 'in_review', to: 'done' }],
          createdAt: issue.completedAt,
        });
      }
    }
    // Raw driver insert so our historical createdAt values aren't overwritten by Mongoose timestamps.
    await IssueModel.collection.insertMany(issues);
    console.log(`[seed] ${def.name}: ${issues.length} issues`);
  }

  await CommentModel.collection.insertMany(commentDocs);
  await ActivityModel.collection.insertMany(activityDocs);
  await NotificationModel.insertMany(
    users.slice(1, 4).map((actor, i) => ({
      user: users[0]!._id,
      actor: actor._id,
      kind: 'commented',
      message: ['commented on WEB-3: “Pushed a draft PR”', 'assigned you to API-12', 'moved MOB-4 to Done'][i],
      link: '/',
      read: false,
    })),
  );

  console.log(`[seed] ${commentDocs.length} comments, ${activityDocs.length} activity entries`);
  console.log('[seed] done. Log in with demo@sprintly.dev / password123');
  await disconnectDb();
}

main().catch(async (err) => {
  console.error(err);
  await disconnectDb();
  process.exit(1);
});
